def normalize_phone_number(country_code, local_number):
    code = (country_code or '').strip()
    number = re.sub(r'\s+', '', (local_number or '').strip())
    if not number:
        return ''
    if code and number.startswith(code):
        return number
    if code:
        return f'{code}{number}'
    return number


def split_phone_number(phone_number):
    raw = re.sub(r'\s+', '', (phone_number or '').strip())
    if not raw:
        return '', ''

    codes = sorted((choice[0] for choice in PHONE_CODE_CHOICES if choice[0]), key=len, reverse=True)
    for code in codes:
        if raw.startswith(code):
            return code, raw[len(code):]

    return '', raw